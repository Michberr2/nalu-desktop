import assert from 'node:assert/strict'
const visible=selector=>`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)return false;const r=e.getBoundingClientRect();return r.width>0&&r.height>0&&r.left>=0&&r.top>=0&&r.right<=innerWidth+1&&r.bottom<=innerHeight+1})()`
export async function verifyAvatarDesktop(api){
 const {js,call,click,button,wait,screenshot,record,replies,taskFeed,file,project}=api
 await call('Emulation.setDeviceMetricsOverride',{width:1360,height:900,deviceScaleFactor:1,mobile:false})
 await wait(()=>js(`document.querySelector('.avatar-home [data-ready=true]')!==null`),'home avatar ready')
 assert.ok(await js(`!!document.querySelector('.appearance-avatar')`))
 assert.equal(await js(`document.querySelector('.avatar-home').textContent.includes("I'm righthere.")`),true)
 assert.equal(await js(`document.querySelectorAll('.avatar-home .nalu-avatar-pause').length`),0)
 await screenshot('avatar-home')
 for(const [width,height] of [[1024,768],[900,600]]){
  await call('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:false})
  for(const selector of ['.app-header','.avatar-home','.avatar-home-actions .avatar-primary'])assert.ok(await js(visible(selector)),selector+' at '+width)
  assert.equal(await js('document.documentElement.scrollWidth>innerWidth'),false)
  await screenshot('avatar-home-'+width)
 }
 await call('Emulation.setDeviceMetricsOverride',{width:1360,height:900,deviceScaleFactor:1,mobile:false})
 record('Avatar home renders at 1360, 1024 and 900 pixels without overflow or demo controls')
 await click('.avatar-home-actions .avatar-primary')
 await wait(()=>js(visible('[aria-label="Chat prompt"]')),'chat opens from home')
 await wait(()=>js(`!!document.querySelector('.chat-avatar-welcome [data-ready=true]')`),'chat avatar')
 await screenshot('avatar-chat')
 await js(`document.querySelector('[aria-label="Chat prompt"]').focus()`);await call('Input.insertText',{text:'Keep this draft'})
 await button('Home');await button('Chats');assert.equal(await js(`document.querySelector('[aria-label="Chat prompt"]').value`),'Keep this draft')
 replies.push('Your redesigned Nalu chat is connected.')
 await click('[aria-label="Send chat message"]')
 await wait(()=>js(`document.querySelector('.chat-messages').textContent.includes('Your redesigned Nalu chat is connected.')`),'chat reply')
 await screenshot('avatar-chat-conversation')
 record('Home opens chat; drafts survive view changes and the existing streaming conversation works')
 taskFeed.push({id:'avatar-active',title:'Preparing the launch',source:'voice',status:'running',updated_at:new Date().toISOString(),events:[]},{id:'avatar-done',title:'Finished research',source:'desktop',status:'done',updated_at:new Date().toISOString(),meta:{result:'Complete'},events:[]})
 await button('Home');await js(`document.querySelectorAll('.avatar-home-destinations button')[1].click()`)
 await wait(()=>js(`document.querySelectorAll('dialog[open] .task-activity-card').length===2`),'task activity')
 await wait(()=>js(`!!document.querySelector('dialog[open] [data-ready=true]')`),'task avatar')
 await screenshot('avatar-autopilot')
 await js(`Array.from(document.querySelectorAll('.task-page-tabs button')).find(b=>b.textContent==='Active').click()`);assert.equal(await js(`document.querySelectorAll('.task-activity-card').length`),1)
 await js(`Array.from(document.querySelectorAll('.task-page-tabs button')).find(b=>b.textContent==='Finished').click()`);assert.ok(await js(`document.querySelector('.task-activity-card').textContent.includes('Finished research')`))
 await click('[aria-label="Close task activity"]')
 await js(`document.querySelectorAll('.avatar-home-destinations button')[2].click()`)
 await wait(()=>js(`!!document.querySelector('dialog[open] form')`),'team role form')
 await wait(()=>js(`!!document.querySelector('dialog[open] [data-ready=true]')`),'team avatar')
 await screenshot('avatar-team');await click('[aria-label="Close your team"]')
 record('Home opens rebuilt AutoPilot and Team; task filters and existing role fields remain available')
 await js(`document.querySelectorAll('.avatar-home-destinations button')[3].click()`)
 await wait(()=>js(`!!document.querySelector('.settings-dialog [data-ready=true]')`),'settings avatar')
 await screenshot('avatar-settings')
 await js(`Array.from(document.querySelectorAll('.appearance-options button')).find(b=>b.textContent.startsWith('Focus')).click()`)
 assert.equal(await js(`localStorage.getItem('nalu-avatar-appearance')`),'focus')
 await js(`Array.from(document.querySelectorAll('.appearance-options button')).find(b=>b.textContent.startsWith('Nalu')).click()`)
 await click('[aria-label="Close settings"]')
 await button('Workspace');await wait(()=>js(visible('.welcome-primary')),'workspace welcome')
 await wait(()=>js(`!!document.querySelector('.workspace-welcome [data-ready=true]')`),'workspace avatar')
 await screenshot('avatar-workspace')
 await js(`window.nalu.saveWorkspace(${JSON.stringify(JSON.stringify({version:1,folder:project,tabs:[{path:file,name:'first.txt'}],activePath:file}))})`)
 await call('Page.reload');await wait(()=>js(`document.querySelector('.view-lines')?.textContent.includes('FIRST_ORIGINAL')`),'real editor file')
 assert.equal(await js(`getComputedStyle(document.querySelector('.monaco-editor')).backgroundColor`),'rgb(255, 255, 255)')
 await click('[aria-label="Toggle terminal"]');await wait(()=>js(`!!document.querySelector('.xterm')`),'terminal opens')
 await screenshot('avatar-editor-terminal')
 await button('Home');await button('Workspace');assert.ok(await js(`!!document.querySelector('.xterm')`))
 assert.ok(await js(`document.querySelector('.view-lines')?.textContent.includes('FIRST_ORIGINAL')`))
 for(const [width,height] of [[1100,760],[900,600]]){
  await call('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:false})
  for(const selector of ['[aria-label="Send prompt"]','[aria-label="Nalu work mode"]'])assert.ok(await js(visible(selector)),selector+' at '+width)
  assert.equal(await js('document.documentElement.scrollWidth>innerWidth'),false)
  await screenshot('avatar-editor-'+width)
 }
 record('Settings persists appearance; real Monaco and terminal match the avatar palette and survive Home/Workspace switching')
}
